#!/usr/bin/env node
// Regenerates packages/tokens/src/primitive/color.json's 7 hue scales in OKLCH.
//
// Phase 1/2 generated these scales with plain HSL math, which isn't perceptually
// uniform — equal HSL lightness steps don't read as equal visual steps, especially
// through the midtones (this produced the real text.success AA failure fixed in
// Phase 3). OKLCH's L channel is designed to be perceptually uniform, so an evenly
// spaced L curve produces evenly spaced *visual* steps.
//
// Two scales carry an exact brand-mandated anchor hex (purple-600 = #5548A4,
// emerald-600 = #2E8A7D, per guidelines/01-vision-and-goals.md's decisions log) —
// for those, every other step is generated by shifting a shared canonical L/chroma
// curve so it passes exactly through the anchor's own OKLCH decomposition at 600.
// The other 5 scales (gray, red, amber, green, blue) have no anchor requirement and
// regenerate fully from the canonical curve, using their current 600 value only to
// pick a matching hue/peak-chroma so the scale keeps its existing color identity.
//
// A third kind, yellow, is anchored (yellow-600 = #949415) but also carries its own
// chroma curve — see TUNED_ANCHORED_SCALES below for why.
//
// Re-run this whenever a scale needs re-deriving (e.g. adding a 3rd brand theme):
//   node packages/tokens/scripts/generate-color-scales.mjs
//
// A full run overwrites src/primitive/color.json's hue scales (including the two
// manual purple overrides noted in guidelines/03-token-system-spec.md); "neutral"
// (white/black) is left untouched since it isn't a hue-based scale. To (re)generate
// one scale without touching any other, pass --only:
//   node packages/tokens/scripts/generate-color-scales.mjs --only=yellow

import { converter, formatHex, clampChroma } from 'culori';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const COLOR_JSON_PATH = join(__dirname, '..', 'src', 'primitive', 'color.json');

const STEPS = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];

// Perceptually-spaced OKLCH lightness per step, calibrated so 50 sits near white
// and 950 sits near black without hitting either extreme (pure white/black at the
// scale ends reads as harsh and loses the last bit of usable contrast range).
const CANONICAL_L = {
  '50': 0.985, '100': 0.955, '200': 0.9, '300': 0.825, '400': 0.74,
  '500': 0.65, '600': 0.56, '700': 0.47, '800': 0.38, '900': 0.29, '950': 0.2,
};

// Chroma relative to the step-600 value — saturation tapers toward both ends since
// the sRGB gamut's max chroma shrinks toward zero near white/black regardless of
// hue; clampChroma() below handles any step that's still out of gamut after this.
const CHROMA_MULTIPLIER = {
  '50': 0.05, '100': 0.12, '200': 0.32, '300': 0.55, '400': 0.8,
  '500': 0.95, '600': 1, '700': 0.9, '800': 0.72, '900': 0.55, '950': 0.38,
};

const toOklch = converter('oklch');

// Anchored scales whose chroma doesn't follow CHROMA_MULTIPLIER. That curve tapers
// toward the light end the way blue or purple do, but yellow's gamut is widest at
// high lightness, so the same taper leaves its light steps a dull olive-grey
// (yellow-50 and -100 would read as near-white greys, and a highlight marker drawn
// from them would barely show). Each light step instead takes a fixed share of the
// largest chroma sRGB can show at that lightness and hue, which keeps it plainly
// yellow; 600 is still the exact anchor, and steps 700 and darker hold one share.
// A documented exception to the shared curve (see ADR-0042).
const TUNED_ANCHORED_SCALES = {
  yellow: {
    anchor: '#949415',
    chromaShareOfGamutMax: {
      '50': 0.3, '100': 0.52, '200': 0.68, '300': 0.76, '400': 0.8, '500': 0.83,
      '700': 0.85, '800': 0.85, '900': 0.85, '950': 0.85,
    },
  },
};

// Brand-anchored scales: exact hex required at 600 (guidelines/01-vision-and-goals.md
// decisions log). Every other step is the canonical L curve shifted by a constant
// offset so it passes through the anchor's own L at 600 — this preserves the
// curve's perceptual spacing while still hitting the required color exactly.
const ANCHORED_SCALES = {
  purple: '#5548A4',
  emerald: '#2E8A7D',
};

// Free scales: no anchor requirement. Use the canonical L curve directly, and pick
// hue/peak-chroma from the scale's current 600 value so it keeps its existing
// color identity (red stays red, etc.) while gaining OKLCH's even step spacing.
const FREE_SCALES = {
  gray: '#69657B',
  red: '#B62F2B',
  amber: '#C4871C',
  green: '#419F64',
  blue: '#3262AE',
};

function clampL(l) {
  return Math.min(0.99, Math.max(0.03, l));
}

function toHex({ l, c, h }) {
  const inGamut = clampChroma({ mode: 'oklch', l: clampL(l), c, h }, 'oklch', 'rgb');
  return formatHex(inGamut).toUpperCase();
}

// How much of the anchor's L-offset each step carries: 0 = canonical lightness
// (unshifted, same as the free scales), 1 = full offset (exact anchor
// continuity). 600 is always 1 by construction (it *is* the anchor).
//
// First attempt (2026-07-27) used a hard on/off cutoff — steps 50/100/200
// unshifted, 300+ fully shifted — to fix purple's 50/100/200 reading as
// gray/washed-out instead of light tints (root cause: purple-600's OKLCH L
// sits well below the curve's own 600 midpoint, 0.46 vs 0.56, so a constant
// offset dragged the whole light end down toward mid-gray). That fixed
// 50-200 but left a real, measurable discontinuity in the L curve: the
// 200->300 gap was 0.171, nearly double every other gap in the scale
// (~0.09) — because 200 jumped to fully-unshifted while 300 stayed at the
// old fully-shifted value with nothing in between. That cliff is what read
// as "300 still looks gray" on inspection (2026-07-27 follow-up): 300 sat
// perceptibly darker than a smoothly-spaced curve would put it, which reads
// muddier at that chroma level.
//
// Fixed by ramping the offset in linearly across 200->600 instead of
// snapping it on at 300. This keeps the light end (50-200) fully unshifted
// as before, restores an even L curve with no cliff anywhere, and still
// lands exactly on the anchor at 600.
const OFFSET_BLEND = {
  '50': 0, '100': 0, '200': 0, '300': 0.25, '400': 0.5, '500': 0.75,
  '600': 1, '700': 1, '800': 1, '900': 1, '950': 1,
};

function generateAnchoredScale(hex) {
  const anchor = toOklch(hex);
  const lOffset = anchor.l - CANONICAL_L['600'];
  const scale = {};
  for (const step of STEPS) {
    if (step === '600') {
      // Hardcoded rather than round-tripped through OKLCH conversion — guarantees
      // byte-identical anchor preservation rather than relying on float round-trip.
      scale[step] = hex.toUpperCase();
      continue;
    }
    const l = CANONICAL_L[step] + lOffset * OFFSET_BLEND[step];
    const c = anchor.c * CHROMA_MULTIPLIER[step];
    scale[step] = toHex({ l, c, h: anchor.h });
  }
  return scale;
}

function generateTunedAnchoredScale({ anchor: hex, chromaShareOfGamutMax }) {
  const anchor = toOklch(hex);
  const lOffset = anchor.l - CANONICAL_L['600'];
  const scale = {};
  for (const step of STEPS) {
    if (step === '600') {
      scale[step] = hex.toUpperCase();
      continue;
    }
    const l = clampL(CANONICAL_L[step] + lOffset * OFFSET_BLEND[step]);
    // The largest in-gamut chroma at this lightness and hue.
    const gamutMax = clampChroma({ mode: 'oklch', l, c: 0.4, h: anchor.h }, 'oklch', 'rgb').c ?? 0;
    scale[step] = toHex({ l, c: gamutMax * chromaShareOfGamutMax[step], h: anchor.h });
  }
  return scale;
}

function generateFreeScale(hex) {
  const anchor = toOklch(hex);
  const scale = {};
  for (const step of STEPS) {
    const l = CANONICAL_L[step];
    const c = anchor.c * CHROMA_MULTIPLIER[step];
    scale[step] = toHex({ l, c, h: anchor.h });
  }
  return scale;
}

function toTokenShape(scale) {
  const out = {};
  for (const step of STEPS) {
    out[step] = { $type: 'color', $value: scale[step] };
  }
  return out;
}

const current = JSON.parse(readFileSync(COLOR_JSON_PATH, 'utf-8'));

const generators = {
  purple: () => toTokenShape(generateAnchoredScale(ANCHORED_SCALES.purple)),
  emerald: () => toTokenShape(generateAnchoredScale(ANCHORED_SCALES.emerald)),
  gray: () => toTokenShape(generateFreeScale(FREE_SCALES.gray)),
  red: () => toTokenShape(generateFreeScale(FREE_SCALES.red)),
  amber: () => toTokenShape(generateFreeScale(FREE_SCALES.amber)),
  yellow: () => toTokenShape(generateTunedAnchoredScale(TUNED_ANCHORED_SCALES.yellow)),
  green: () => toTokenShape(generateFreeScale(FREE_SCALES.green)),
  blue: () => toTokenShape(generateFreeScale(FREE_SCALES.blue)),
};

// `--only=<scale>` regenerates that one scale and leaves every other value in the file as it is.
const only = process.argv.find((arg) => arg.startsWith('--only='))?.slice('--only='.length);
if (only !== undefined && !(only in generators)) {
  console.error(`Unknown scale "${only}". Choose one of: ${Object.keys(generators).join(', ')}`);
  process.exit(1);
}

let result;
if (only === undefined) {
  // Keeps the file's order: purple, emerald, gray, red, amber, yellow, green, blue, neutral.
  const ordered = {};
  for (const name of Object.keys(generators)) ordered[name] = generators[name]();
  result = { ...ordered, neutral: current.neutral };
} else {
  result = {};
  for (const [name, value] of Object.entries(current)) {
    result[name] = name === only ? generators[only]() : value;
    // A scale that isn't in the file yet goes right after amber, where it reads in the scale order.
    if (name === 'amber' && !(only in current) && only === 'yellow') result.yellow = generators.yellow();
  }
}

writeFileSync(COLOR_JSON_PATH, JSON.stringify(result, null, 2) + '\n');

console.log('Regenerated', COLOR_JSON_PATH);
for (const [name, scale] of Object.entries(result)) {
  if (name === 'neutral' || (only !== undefined && name !== only)) continue;
  console.log(`\n${name}:`);
  for (const step of STEPS) {
    console.log(`  ${step.padStart(3)}: ${scale[step].$value}`);
  }
}
